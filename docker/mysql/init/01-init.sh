#!/bin/sh
set -e

# Creates the four service databases and their dedicated users from environment variables.
# Runs only on an empty MySQL data volume.

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE DATABASE IF NOT EXISTS auth_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS course_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS payment_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS notification_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS '${AUTH_DB_USER}'@'%' IDENTIFIED BY '${AUTH_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${COURSE_DB_USER}'@'%' IDENTIFIED BY '${COURSE_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${PAYMENT_DB_USER}'@'%' IDENTIFIED BY '${PAYMENT_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${NOTIFICATION_DB_USER}'@'%' IDENTIFIED BY '${NOTIFICATION_DB_PASSWORD}';

GRANT ALL PRIVILEGES ON auth_db.* TO '${AUTH_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON course_db.* TO '${COURSE_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON payment_db.* TO '${PAYMENT_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON notification_db.* TO '${NOTIFICATION_DB_USER}'@'%';

FLUSH PRIVILEGES;
SQL
